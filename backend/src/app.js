import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import {rateLimit} from 'express-rate-limit';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import authRoutes from './routes/auth.js';
import workspaceRoutes from './routes/workspace.js';
import auditorRoutes from './routes/auditor.js';
import contractorRoutes from './routes/contractors.js';
import reportRoutes from './routes/reports.js';
import siteRoutes from './routes/sites.js';
import platformRoutes from './routes/platform.js';
import digestRoutes from './routes/digest.js';
const app=express();
app.disable('x-powered-by');
app.use(helmet({contentSecurityPolicy:false,crossOriginEmbedderPolicy:false}));
app.use(cors({origin:(process.env.CORS_ORIGIN||'http://localhost:8080').split(',').map(x=>x.trim()),credentials:false}));
app.use(express.json({limit:'2mb'}));
app.use(rateLimit({windowMs:15*60*1000,limit:500,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(req,res)=>res.json({ok:true,service:'JEZTECH SafetyOS API',time:new Date().toISOString()}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.use('/api',workspaceRoutes);
app.use('/api/v1/auditor',auditorRoutes);
app.use('/api/v1/contractors',contractorRoutes);
app.use('/api/v1/reports',reportRoutes);
app.use('/api/sites',siteRoutes);
app.use('/api/platform',platformRoutes);
app.use('/api/v1/auditor',digestRoutes);
app.use('/api',(req,res)=>res.status(404).json({error:'API endpoint not found.'}));
const here=path.dirname(fileURLToPath(import.meta.url));
app.use(express.static(path.resolve(here,'../../frontend')));
app.get('*',(req,res)=>res.sendFile(path.resolve(here,'../../frontend/index.html')));
app.use((err,req,res,next)=>{if(res.headersSent)return next(err);if(err?.name==='ZodError')return res.status(400).json({error:'Validation failed.',details:err.issues.map(i=>({field:i.path.join('.'),message:i.message}))});const status=err.status||(err.code==='23505'?409:500);if(status>=500)console.error(err);res.status(status).json({error:status===500?'An unexpected server error occurred.':err.message});});
export default app;
